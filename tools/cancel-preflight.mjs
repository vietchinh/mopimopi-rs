#!/usr/bin/env node
// Writes css/cancel-preflight.css: the block that undoes Tailwind's Preflight.
//
// `@import "tailwindcss"` (the Dioxus guide's first line) brings in Preflight, a reset applied to every element. The overlay is a port of a page
// that never had it, so its effects (box-sizing:border-box, `img{display:block}`, borders, list and heading resets, ...) are cancelled: for every
// selector Preflight styles, the same properties are set to `revert-layer` in the same layer, later, which rolls each one back to what it was before
// the `base` layer, i.e. the browser's own default. Generated from Preflight itself, so nothing is listed by hand; run it again after upgrading Tailwind:
//
//   node tools/cancel-preflight.mjs            write css/cancel-preflight.css
//   node tools/cancel-preflight.mjs --check    fail if that file is out of date (build.sh and the test suite run this)
//   node tools/cancel-preflight.mjs --print    print it instead
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const preflight = fs.readFileSync(createRequire(path.join(root, "package.json")).resolve("tailwindcss/preflight.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");

/** `selector { decls }` and `@at-rule (...) { rules }`, by brace matching. */
function parse(text) {
  const nodes = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    let depth = 1, j = open + 1;
    while (depth && j < text.length) depth += text[j] === "{" ? 1 : text[j] === "}" ? -1 : 0, j++;
    nodes.push({ head: text.slice(i, open).trim().replace(/\s+/g, " "), body: text.slice(open + 1, j - 1) });
    i = j;
  }
  return nodes;
}

function emit(nodes, indent) {
  return nodes.map(({ head, body }) => {
    if (head.startsWith("@")) return `${indent}${head} {\n${emit(parse(body), indent + "  ")}${indent}}\n`;
    const declarations = [...body.matchAll(/([\w-]+)\s*:[^;]*?(\s*!important)?\s*(?:;|$)/g)].map((m) => ({ property: m[1], important: !!m[2] }));
    const unique = [...new Map(declarations.map((d) => [d.property, d])).values()];
    const selectors = head.split(",").map((s) => s.trim()).join(`,\n${indent}`);
    return `${indent}${selectors} {\n${unique.map((d) => `${indent}  ${d.property}: revert-layer${d.important ? " !important" : ""};`).join("\n")}\n${indent}}\n`;
  }).join("");
}

const HEADER = `/* Preflight, undone. Generated by \`node tools/cancel-preflight.mjs\` from Tailwind's Preflight; do not edit.
   \`@import "tailwindcss"\` includes Preflight, a reset applied to every element (box-sizing:border-box, \`img{display:block}\`, \`border:0 solid\`,
   list and heading resets, ...). The overlay is a port of a page that never had it, and with it the size of ~230 elements changed. So for every
   selector Preflight styles, the same properties are set to \`revert-layer\` here, in the same layer and later: that rolls each one back to the
   browser's own default. */
`;
const block = HEADER + `@layer base {\n${emit(parse(preflight), "  ")}}\n`;
const target = path.join(root, "css", "cancel-preflight.css");
if (process.argv.includes("--print")) process.stdout.write(block);
else if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== block) { console.error("css/cancel-preflight.css is missing or out of date; regenerate it with `node tools/cancel-preflight.mjs`"); process.exit(1); }
  console.log("ok: css/cancel-preflight.css is up to date");
} else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, block); console.log("wrote css/cancel-preflight.css"); }
